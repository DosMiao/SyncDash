/// Write an exclude back into the job's exclude list. Pruning during the scan only takes effect at the
/// next Compare, so the message has to say so and leave an undo behind.
async function addExclude(mask: string) {
  if (!currentJob) return;
  const name = currentJob.name;
  try {
    const j = await invoke<JobFull>('get_job', { name });
    if (j.exclude.includes(mask)) { setStatus(`The job already has this exclude: ${mask}`); return; }
    const prev = [...j.exclude];
    await invoke('save_job', { name, job: { ...j, exclude: [...prev, mask] } });
    jobs = await invoke<JobDto[]>('list_jobs');
    currentJob = jobs.find((x) => x.name === name) ?? currentJob;
    renderJobs();
    setStatusUndo(`Added to exclude: ${mask} — takes effect after the next Compare (Ctrl+R)`, 'Undo exclude', async () => {
      const cur = await invoke<JobFull>('get_job', { name });
      await invoke('save_job', { name, job: { ...cur, exclude: prev } });
      jobs = await invoke<JobDto[]>('list_jobs');
      currentJob = jobs.find((x) => x.name === name) ?? currentJob;
      renderJobs();
      setStatus(`Exclude undone: ${mask}`);
    });
  } catch (e) {
    setStatus(`Failed to write exclude: ${e}`, 'err');
  }
}

function openCtx(x: number, y: number, items: CtxItem[]) {
  ctxEl.innerHTML = '';
  for (const it of items) {
    if (it.sep) {
      const d = document.createElement('div');
      d.className = 'ctxsep';
      ctxEl.appendChild(d);
      continue;
    }
    const d = document.createElement('div');
    d.className = 'ctxitem' + (it.disabled ? ' off' : '') + (it.danger ? ' danger' : '');
    d.textContent = it.label;
    if (!it.disabled && it.run) {
      d.addEventListener('click', (e) => { e.stopPropagation(); closeCtx(); it.run!(); });
    }
    ctxEl.appendChild(d);
  }
  // Positioning goes through CSSOM: a style="" attribute is blocked by the nonce CSP
  ctxEl.classList.remove('hidden');
  const w = ctxEl.offsetWidth, h = ctxEl.offsetHeight;
  // Lower bound 6: when the window is narrower than the menu, min() goes negative and the menu leaves the screen entirely
  ctxEl.style.left = `${Math.max(6, Math.min(x, window.innerWidth - w - 6))}px`;
  ctxEl.style.top = `${Math.max(6, Math.min(y, window.innerHeight - h - 6))}px`;
}

function rowMenu(i: number, x: number, y: number) {
  const p = plan!;
  const op = eff(i);
  const [sp, tp] = sidePaths(op);
  const sAbs = sp ? fullPath(p.header.source_root, sp) : null;
  const tAbs = tp ? fullPath(p.header.target_root, tp) : null;
  const rel = op.path;
  const base = baseOf(rel);
  const dot = base.lastIndexOf('.');
  const ext = dot > 0 ? base.slice(dot + 1) : '';
  const dir = dirOf(rel);
  const canFlip = !!p.reversed[i] && selectable(p.ops[i]);
  const sameDir = visibleIdx().filter((k) => dirOf(eff(k).path) === dir && selectable(eff(k)));
  const items: CtxItem[] = [
    { label: 'Show in Explorer · source', disabled: !sAbs, run: () => { invoke('reveal', { path: sAbs }).catch((e) => setStatus(String(e), 'err')); } },
    { label: 'Show in Explorer · target', disabled: !tAbs, run: () => { invoke('reveal', { path: tAbs }).catch((e) => setStatus(String(e), 'err')); } },
    { sep: true, label: '' },
    { label: 'Copy full path', run: () => copyText((sAbs ?? tAbs)!) },
    { label: 'Copy relative path', run: () => copyText(rel) },
    { sep: true, label: '' },
    { label: ext ? `Exclude this type */*.${ext}` : 'Exclude this type (no extension)', disabled: !ext || !currentJob, run: () => addExclude(`*/*.${ext}`) },
    { label: dir ? `Exclude this directory /${dir}/` : 'Exclude this directory (already at the root)', disabled: !dir || !currentJob, run: () => addExclude(`/${dir}/`) },
    { sep: true, label: '' },
    { label: flipped[i] ? 'Restore original direction' : 'Reverse this row', disabled: !canFlip, run: () => { flipped[i] = !flipped[i]; renderAll(true); } },
    { label: 'Check only this item', run: () => { checked = checked.map((_, k) => k === i && selectable(eff(k))); renderTable(true); } },
    { label: `Uncheck this directory (${sameDir.length})`, disabled: sameDir.length === 0, run: () => { for (const k of sameDir) checked[k] = false; renderTable(true); } },
  ];
  openCtx(x, y, items);
}

