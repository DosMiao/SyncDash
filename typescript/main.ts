/// Mask matching goes to Rust (200 ms debounce): the frontend never writes its own glob,
/// or a mask that worked in the UI could behave differently once written into exclude.
async function recomputeMasks() {
  if (!plan) { maskHit = []; return; }
  if (vfilter.masks.length === 0) {
    maskHit = new Array(plan.ops.length).fill(false);
    return;
  }
  try {
    maskHit = await invoke<boolean[]>('mask_match', {
      masks: vfilter.masks,
      paths: plan.ops.map((_, i) => eff(i).path),
    });
  } catch (e) {
    maskHit = new Array(plan.ops.length).fill(false);
    setStatus(`Mask matching failed: ${e}`, 'err');
  }
}

