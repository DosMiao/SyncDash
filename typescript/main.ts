// P1: drag a directory onto a path box
//
// Tauri v2 has dragDropEnabled on by default, so HTML5 drop events never reach the webview —
// you must go through onDragDropEvent, and payload.position is in **physical pixels**, to be converted to CSS pixels yourself.

/// While the editor is open only its fields count; otherwise the two roots on the main screen do — both accept drops
function dropZone(): HTMLInputElement[] {
  const root = editModal.classList.contains('hidden') ? pathEl : edForm;
  return [...root.querySelectorAll<HTMLInputElement>('input[data-drop]')].filter((el) => !el.disabled);
}

function dropTargetAt(px: number, py: number): HTMLInputElement | null {
  const r = window.devicePixelRatio || 1;
  const x = px / r, y = py / r;
  for (const el of dropZone()) {
    const b = el.getBoundingClientRect();
    if (x >= b.left && x <= b.right && y >= b.top && y <= b.bottom) return el;
  }
  return null;
}

function clearDropHint() {
  for (const el of document.querySelectorAll<HTMLInputElement>('input[data-drop]')) el.classList.remove('dropon');
}

async function wireDragDrop() {
  await getCurrentWebview().onDragDropEvent((ev) => {
    const p = ev.payload as unknown as { type: string; paths?: string[]; position?: { x: number; y: number } };
    if (p.type === 'leave') { clearDropHint(); return; }
    const pos = p.position;
    if (!pos) return;
    const el = dropTargetAt(pos.x, pos.y);
    if (p.type === 'over' || p.type === 'enter') {
      clearDropHint();
      if (el) el.classList.add('dropon');
      return;
    }
    if (p.type !== 'drop') return;
    clearDropHint();
    const first = p.paths?.[0];
    if (!el || !first) return;
    void (async () => {
      // If a file was dropped, take its parent directory — a root field wants a directory
      let v = first;
      try {
        const info = await invoke<PathVerdict>('inspect_paths', { source: first, target: '' });
        if (info.source.exists && !info.source.is_dir) {
          const i = Math.max(v.lastIndexOf('\\'), v.lastIndexOf('/'));
          if (i > 0) v = v.slice(0, i);
        }
      } catch { /* if we can't tell, fill it in as-is */ }
      el.value = v;
      pushHistory(v);
      refreshPathDatalist();
      // Dropping on the two main-screen roots edits the job right away (same path as typing and pressing Enter); in the editor it waits for save
      if (el === pSource) await saveRootFromMain('source', v);
      else if (el === pTarget) await saveRootFromMain('target', v);
      else { edVerdict(); setStatus(`Filled in: ${v}`); }
    })();
  });
}

