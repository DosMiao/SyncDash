/// Native dialog. The @tauri-apps/plugin-dialog npm package is just a wrapper around this one invoke,
/// so calling IPC directly saves a frontend dependency (tauri_plugin_dialog is already registered on the Rust side).
async function pickPath(opts: { directory?: boolean; save?: boolean; title: string; defaultPath?: string }): Promise<string | null> {
  const { directory, save, title, defaultPath } = opts;
  try {
    const r = await invoke<unknown>(save ? 'plugin:dialog|save' : 'plugin:dialog|open', {
      options: { title, defaultPath: defaultPath || undefined, directory: !!directory, multiple: false, recursive: false },
    });
    if (!r) return null;
    // Depending on the patch version, open may return string | string[] | {path}
    const one = Array.isArray(r) ? r[0] : r;
    if (typeof one === 'string') return one;
    if (one && typeof one === 'object' && typeof (one as { path?: string }).path === 'string') return (one as { path: string }).path;
    return null;
  } catch (e) {
    setStatus(`Can't open the picker: ${e}`, 'err');
    return null;
  }
}

/// Path history uses a native datalist (keyboard-friendly, no custom popup layer). It lives at document
/// level: both the editor and the main path row need it, so it can't exist only while the editor is open.
function refreshPathDatalist() {
  const dl = document.getElementById('sd-paths');
  if (!dl) return;
  dl.innerHTML = '';
  for (const p of pathHistory()) {
    const o = document.createElement('option');
    o.value = p;
    dl.appendChild(o);
  }
}

const HIST_KEY = 'sd.pathhist';
function pathHistory(): string[] {
  try { return JSON.parse(localStorage.getItem(HIST_KEY) ?? '[]') as string[]; } catch { return []; }
}
function pushHistory(p: string) {
  const v = p.trim();
  if (!v) return;
  const list = [v, ...pathHistory().filter((x) => x.toLowerCase() !== v.toLowerCase())].slice(0, 12);
  localStorage.setItem(HIST_KEY, JSON.stringify(list));
}

