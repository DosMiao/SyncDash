async function doCompare() {
  if (!currentJob || busy) return;
  sameShow(false); // a new compare = a new snapshot, so the old identical-items list is stale
  setBusy(true);
  setStatus(`Comparing '${currentJob.name}' ...`);
  // v0.9.1 first-principles redesign: compare progress renders in place in the diff-table area — the main
  // window is already in front, so no separate window (no flash on small trees, live per-side counts on big ones, no child-window lifecycle)
  cmpShow();
  try {
    acknowledged = false;
    modalOk.disabled = false;
    plan = await invoke<PlanDto>('compare_job', { name: currentJob.name, targetIndex: selTarget });
    checked = plan.ops.map((op) => selectable(op));
    flipped = plan.ops.map(() => false);
    chips.clear();
    ovFilter = null; ovExpanded.clear(); sort = null;
    // New plan = new row set, so the mask cache is stale; the funnel criteria themselves persist (watching the same files for several rounds is common)
    await recomputeMasks();
    renderFunnelBtn();
    renderAll();
    setStatus(
      plan.ops.length === 0
        ? `'${currentJob.name}' both sides identical ✓`
        : `'${currentJob.name}': ${plan.ops.length} items, ${plan.header.conflict_count} conflicts — review, then Synchronize (Enter)`,
      plan.header.conflict_count > 0 ? 'err' : '',
    );
  } catch (e) {
    plan = null;
    renderAll();
    setStatus(String(e) === 'cancelled' ? 'Compare cancelled' : `Compare failed: ${e}`, String(e) === 'cancelled' ? '' : 'err');
  }
  cmpHide();
  setBusy(false);
}

/// Final action set = checked ∩ currently visible.
/// FFS semantics: "the view is the action set" — what you can't see doesn't run. This also closes a quiet
/// hole in the old behavior, where filtering with the search box still let hidden rows ride along on Synchronize.
function finalIdx(): number[] {
  const vis = new Set(visibleIdx());
  return checked.map((c, i) => (c && vis.has(i) ? i : -1)).filter((i) => i >= 0);
}

async function openConfirm() {
  if (!currentJob || !plan || busy) return;
  const idx = finalIdx();
  const hiddenChecked = checked.filter(Boolean).length - idx.length;
  if (idx.length === 0) {
    setStatus(hiddenChecked > 0 ? 'Every checked row is hidden by a filter — clear the filter first' : 'Nothing is checked', 'err');
    return;
  }
  const cnt = { copy: 0, update: 0, move: 0, del: 0 };
  let bytes = 0, delBytes = 0;
  for (const i of idx) {
    const op = eff(i);
    if (op.action === 'copy') { cnt.copy++; bytes += op.size ?? 0; }
    else if (op.action === 'update') { cnt.update++; bytes += op.size ?? 0; }
    else if (op.action === 'move') cnt.move++;
    else if (op.action === 'delete' || op.action === 'delete_dir') { cnt.del++; delBytes += op.size ?? 0; }
  }
  modalBody.innerHTML = `
    <div class="mrow"><span>Job</span><b>${currentJob.name}</b><span class="mode ${currentJob.mode}">${currentJob.mode}</span></div>
    <div class="mrow"><span>Copy / update</span><b>${cnt.copy} / ${cnt.update}</b><span class="dim">${humanSize(bytes) || '0 B'}</span></div>
    <div class="mrow"><span>Move (no re-transfer)</span><b>${cnt.move}</b></div>
    <div class="mrow ${cnt.del ? 'danger' : ''}"><span>Delete (into the trash)</span><b>${cnt.del}</b><span class="dim">${cnt.del ? humanSize(delBytes) : ''}</span></div>
    ${flipped.some(Boolean) ? `<div class="mrow warn"><span>Of those, reversed</span><b>${flipped.filter(Boolean).length}</b></div>` : ''}
    ${hiddenChecked > 0 ? `<div class="mrow warn"><span>Hidden by filter, not run</span><b>${hiddenChecked}</b><span class="dim">The view is the action set</span></div>` : ''}
  `;
  modalEl.classList.remove('hidden');

  // Gate checks (free disk space / delete ratio) — the reasons belong in front of the user before
  // Synchronize is pressed, not surfacing at run time in an invisible stderr line
  try {
    const pf = await invoke<PreflightDto>('preflight', {
      name: currentJob.name, plan, ops: idx.map((i) => eff(i)), acknowledged: acknowledged, targetIndex: selTarget,
    });
    for (const w of pf.warnings) {
      modalBody.innerHTML += `<div class="mrow warn"><span>Warning</span><span class="dim">${escapeHtml(w)}</span></div>`;
    }
    if (!pf.ok) {
      for (const b of pf.blockers) {
        modalBody.innerHTML += `<div class="mrow danger"><span>Blocked</span><span class="dim">${escapeHtml(b)}</span></div>`;
      }
      modalBody.innerHTML += `<div class="mrow"><label><input type="checkbox" id="ackbox"> I confirm this is correct, continue (same as the CLI's --i-know)</label></div>`;
      const box = document.getElementById('ackbox') as HTMLInputElement | null;
      if (box) box.onchange = () => { acknowledged = box.checked; };
      modalOk.disabled = true;
      if (box) box.addEventListener('change', () => { modalOk.disabled = !box.checked; });
    } else {
      modalOk.disabled = false;
    }
  } catch (e) {
    modalBody.innerHTML += `<div class="mrow danger"><span>Check failed</span><span class="dim">${escapeHtml(String(e))}</span></div>`;
  }
}

function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!));
}

async function doSync() {
  modalEl.classList.add('hidden');
  if (!currentJob || !plan || busy) return;
  const idx = finalIdx();
  const finalOps = idx.map((i) => eff(i));
  setBusy(true);
  setStatus(`Synchronizing '${currentJob.name}' (${finalOps.length} items)...`);
  // Whether the progress window stays during a sync is its own Auto-close / When-finished business; the main window doesn't touch it
  invoke('open_progress_window').catch(() => {});
  try {
    const r = await invoke<ApplyDto>('apply_job', { name: currentJob.name, plan, ops: finalOps, acknowledged, targetIndex: selTarget });
    setStatus(
      r.cancelled
        ? `Stopped: cancelled after ${r.done} run — re-checking...`
        : `Done: ${r.done} run, ${r.skipped} skipped, ${r.errors} errors — re-checking...`,
      r.errors ? 'err' : 'ok',
    );
    setBusy(false);
    refreshLastSyncs();
    await doCompare();
  } catch (e) {
    setStatus(`Synchronize failed: ${e}`, 'err');
    setBusy(false);
  }
}

