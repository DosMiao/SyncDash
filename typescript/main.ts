const p2 = (n: number) => String(n).padStart(2, '0');
/// This year shows only MM-DD HH:mm; earlier years add the year — the column is narrow, density wins
function fmtTime(ms: number): string {
  if (!ms) return '';
  const d = new Date(ms);
  const md = `${p2(d.getMonth() + 1)}-${p2(d.getDate())} ${p2(d.getHours())}:${p2(d.getMinutes())}`;
  return d.getFullYear() === new Date().getFullYear() ? md : `${d.getFullYear()}-${md}`;
}

/// The op currently in effect for this row (once flipped, the reversed one)
function eff(i: number): OpDto {
  const p = plan!;
  return flipped[i] && p.reversed[i] ? p.reversed[i]! : p.ops[i];
}

function selectable(op: OpDto): boolean {
  return op.action !== 'conflict' && op.action !== 'note';
}

function category(op: OpDto): Chip {
  switch (op.action) {
    case 'copy': return 'copy';
    case 'update': case 'chmod': return 'update';
    case 'move': return 'move';
    case 'delete': case 'delete_dir': return 'delete';
    default: return 'conflict';
  }
}

function dirOf(p: string): string {
  const i = p.lastIndexOf('/');
  return i < 0 ? '' : p.slice(0, i);
}
function baseOf(p: string): string {
  const i = p.lastIndexOf('/');
  return i < 0 ? p : p.slice(i + 1);
}

function sepOf(root: string): string {
  return root.includes('\\') ? '\\' : '/';
}
function fullPath(root: string, rel: string): string {
  const sep = sepOf(root);
  const r = root.endsWith(sep) ? root.slice(0, -1) : root;
  return r + sep + (sep === '\\' ? rel.replace(/\//g, '\\') : rel);
}

/// The paths that **currently exist** on the source / target side for this row (state at compare time, not after the run):
/// copy exists only on the origin side; delete only on the side being deleted; for move the executing side is still `from` while the other is already `path`;
/// update/chmod/conflict/note exist on both sides.
function sidePaths(op: OpDto): [string | null, string | null] {
  const execOnTarget = op.side === 'target';
  switch (op.action) {
    case 'copy':
      return execOnTarget ? [op.path, null] : [null, op.path];
    case 'move': {
      const cur = op.from ?? op.path;
      return execOnTarget ? [op.path, cur] : [cur, op.path];
    }
    case 'delete':
    case 'delete_dir':
      return execOnTarget ? [null, op.path] : [op.path, null];
    default:
      return [op.path, op.path];
  }
}

function matchesSearch(op: OpDto): boolean {
  if (!search) return true;
  const q = search.toLowerCase();
  return op.path.toLowerCase().includes(q)
    || (op.from ?? '').toLowerCase().includes(q)
    || op.reason.toLowerCase().includes(q);
}

function matchesOv(op: OpDto): boolean {
  if (!ovFilter) return true;
  if (ovFilter === '(root)') return !op.path.includes('/');
  return op.path === ovFilter || op.path.startsWith(ovFilter + '/');
}

function metaOf(i: number): RowMeta {
  return plan?.metas?.[i] ?? { src: null, dst: null };
}

/// Sort value [missing flag, numeric key, text key]. A missing side always sorts last (regardless of
/// direction) so "things that aren't there" don't steal attention. Numeric keys compare as numbers — the
/// old code zero-padded size/mtime to 20-char strings, two allocations per comparator call, i.e. hundreds
/// of thousands of them for one pass over a few thousand rows
function sortVal(i: number, key: SortKey): [number, number, string] {
  const op = eff(i);
  const m = metaOf(i);
  switch (key) {
    case 'path': return [0, 0, op.path.toLowerCase()];
    case 'action': return [0, 0, op.action];
    case 's.size': return [m.src ? 0 : 1, m.src?.size ?? 0, ''];
    case 's.mtime': return [m.src ? 0 : 1, m.src?.mtime_ms ?? 0, ''];
    case 't.size': return [m.dst ? 0 : 1, m.dst?.size ?? 0, ''];
    case 't.mtime': return [m.dst ? 0 : 1, m.dst?.mtime_ms ?? 0, ''];
  }
}

/// Bytes and time this row involves: take the larger/newer of the two sides ("how big and how new is the file behind this row")
function rowSize(i: number): number {
  const m = metaOf(i);
  return Math.max(eff(i).size ?? 0, m.src?.size ?? 0, m.dst?.size ?? 0);
}
function rowMtime(i: number): number {
  const m = metaOf(i);
  return Math.max(m.src?.mtime_ms ?? 0, m.dst?.mtime_ms ?? 0);
}

/// Funnel check: hit by a mask = hidden; size/age outside the range = hidden
function passesFunnel(i: number): boolean {
  if (maskHit[i]) return false;
  const MB = 1024 * 1024;
  if (vfilter.minMB !== null || vfilter.maxMB !== null) {
    const sz = rowSize(i);
    if (vfilter.minMB !== null && sz < vfilter.minMB * MB) return false;
    if (vfilter.maxMB !== null && sz > vfilter.maxMB * MB) return false;
  }
  if (vfilter.days !== null) {
    const t = rowMtime(i);
    if (!t || Date.now() - t > vfilter.days * 86400_000) return false;
  }
  return true;
}

function funnelActive(): number {
  return (vfilter.masks.length ? 1 : 0)
    + (vfilter.minMB !== null || vfilter.maxMB !== null ? 1 : 0)
    + (vfilter.days !== null ? 1 : 0);
}

/// visibleIdx is a full-table scan (possibly with a sort), and one renderTable pass asks for it four
/// times downstream: table body, header tri-state checkbox, stats bar (finalIdx), counts bar. The cache
/// lives for a single render — renderTable / renderAll invalidate it up front, so a filter can never read a stale result.
let visCache: number[] | null = null;
function invalidateVis() { visCache = null; }

function visibleIdx(): number[] {
  return visCache ?? (visCache = computeVisible());
}

function computeVisible(): number[] {
  if (!plan) return [];
  const n = plan.ops.length;
  const out: number[] = [];
  for (let i = 0; i < n; i++) {
    const op = eff(i);
    if ((chips.size === 0 || chips.has(category(op))) && matchesSearch(op) && matchesOv(op) && passesFunnel(i)) out.push(i);
  }
  if (sort) {
    const { key, dir } = sort;
    // Precompute the sort keys once: the comparator runs n·log n times, and computing keys inside it
    // means hundreds of thousands of eff()/metaOf() calls plus string allocations
    const miss = new Int8Array(n), num = new Float64Array(n);
    const str: string[] = new Array(n);
    for (const i of out) { const [a, b, c] = sortVal(i, key); miss[i] = a; num[i] = b; str[i] = c; }
    out.sort((a, b) =>
      (miss[a] - miss[b])                                            // missing always last, direction never flips it
      || (num[a] - num[b]) * dir
      || (str[a] < str[b] ? -dir : str[a] > str[b] ? dir : 0)
      || a - b);                                                     // ties keep the plan's original order
  }
  return out;
}

function badge(op: OpDto, canFlip: boolean): [string, string] {
  const toTarget = op.side === 'target';
  let txt = '', cls = '';
  switch (op.action) {
    case 'copy':   txt = toTarget ? '→ copy' : '← copy'; cls = toTarget ? 'copy-r' : 'copy-l'; break;
    case 'update': txt = toTarget ? '→ update' : '← update'; cls = 'update'; break;
    case 'move':   txt = (toTarget ? '→' : '←') + ' move'; cls = 'mv'; break;
    case 'delete':
    case 'delete_dir': txt = (toTarget ? '→' : '←') + ' delete'; cls = 'del'; break;
    case 'chmod':  txt = (toTarget ? '→' : '←') + ' chmod'; cls = 'update'; break;
    case 'conflict': txt = '⚡ conflict'; cls = 'conflict'; break;
    case 'note':   txt = 'ⓘ note'; cls = 'note'; break;
  }
  return [txt, cls + (canFlip ? ' flippable' : '')];
}

