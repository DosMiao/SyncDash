function lpRender() {
  const q = lpQ.value.trim().toLowerCase();
  const rows = lpRows.filter((r) => (lpLevel === 'all' || r.level === lpLevel) && (!q || r.hay.toLowerCase().includes(q) || r.text.toLowerCase().includes(q)));
  lpBody.innerHTML = '';
  if (rows.length === 0) {
    lpBody.innerHTML = `<div class="logempty">${lpRows.length ? 'No matching rows' : 'This artifact is empty'}</div>`;
    lpStat.textContent = `0 / ${lpRows.length}`;
    return;
  }
  // Building DOM for a huge list stalls; the items list routinely runs to tens of thousands of rows, so cap it first
  const CAP = 3000;
  const frag = document.createDocumentFragment();
  for (const r of rows.slice(0, CAP)) {
    const d = document.createElement('div');
    d.className = `lp-row lv-${r.level}`;
    d.innerHTML =
      `<span class="lp-t">${r.ts ? hms(r.ts) : ''}</span>` +
      `<span class="lp-l">${LOG_LEVEL_LABEL[r.level]}</span>` +
      `<span class="lp-s">${escapeHtml(r.scope)}</span>` +
      `<span class="lp-m">${escapeHtml(r.text)}</span>`;
    frag.appendChild(d);
  }
  lpBody.appendChild(frag);
  if (rows.length > CAP) {
    const more = document.createElement('div');
    more.className = 'logempty';
    more.textContent = `Showing the first ${CAP} of ${rows.length} rows — narrow it with search, or click 📂 to open the raw file`;
    lpBody.appendChild(more);
  }
  lpStat.textContent = `${rows.length} / ${lpRows.length}`;
}

