// Virtual scrolling for the table body
// One diff row = <tr> + 7 <td> + checkbox + badge ≈ 10 nodes, 3 listeners. Thousands of those in a live
// <table> cost tens of seconds just to build and to recompute auto column widths — and a chip switch, a
// keystroke in the search box, or folding one directory redoes all of it. So we mount only the viewport's
// rows and pad above and below with spacers that stretch the scrollbar to the real height: render cost
// drops from O(whole table) to O(one screen).

type RowSpec =
  | { kind: 'grp'; dir: string; items: number[] }
  | { kind: 'row'; i: number; groupDir: string | null };

const OVERSCAN = 8;               // extra rows above and below the viewport so fast scrolling never shows blanks
let rowPlan: RowSpec[] = [];      // which rows the current view shows (incl. group headers), already ordered
let rowTop = new Float64Array(1); // prefix sums: rowTop[k] = top offset of row k; rowTop[n] = total height
let hRow = 29, hGrp = 31;         // row heights, backfilled from the first frame (tracks padding/font changes)
let winFrom = -1, winTo = -1;     // the currently mounted window [from, to)
let remeasuring = false;

function layoutRows() {
  const n = rowPlan.length;
  if (rowTop.length < n + 1) rowTop = new Float64Array(n + 1);
  let y = 0;
  for (let k = 0; k < n; k++) { rowTop[k] = y; y += rowPlan[k].kind === 'grp' ? hGrp : hRow; }
  rowTop[n] = y;
  winFrom = winTo = -1; // heights were re-laid out, so any mounted window is stale
}

/// Binary search: the last row whose top is ≤ y
function rowAt(y: number): number {
  let lo = 0, hi = rowPlan.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (rowTop[mid] <= y) lo = mid; else hi = mid - 1;
  }
  return lo;
}

/// Spacer row. Height must be set through CSSOM — a style="" attribute is blocked by the nonce CSP Tauri injects
function spacerRow(h: number): HTMLTableRowElement {
  const tr = document.createElement('tr');
  tr.className = 'vspacer';
  const td = document.createElement('td');
  td.colSpan = 7;
  td.style.height = `${h}px`;
  tr.appendChild(td);
  return tr;
}

/// Mount the slice of rows matching the viewport. force = the row plan just changed, so rebuild even if the window didn't move
function mountWindow(force = false) {
  const n = rowPlan.length;
  if (n === 0) { bodyEl.replaceChildren(); winFrom = winTo = -1; return; }
  // Inside the scrolled content, tbody starts at the height of the sticky header (the panels above the table are display:none)
  const top = Math.max(0, wrapEl.scrollTop - theadEl.offsetHeight);
  const from = Math.max(0, rowAt(top) - OVERSCAN);
  const to = Math.min(n, rowAt(top + wrapEl.clientHeight) + 1 + OVERSCAN);
  if (!force && from === winFrom && to === winTo) return;

  const frag = document.createDocumentFragment();
  if (from > 0) frag.appendChild(spacerRow(rowTop[from]));
  for (let k = from; k < to; k++) {
    const s = rowPlan[k];
    const tr = s.kind === 'grp' ? buildGroupRow(s.dir, s.items) : buildRow(s.i, s.groupDir);
    // Zebra striping keys off the real row index, not :nth-child — otherwise the stripes flip as the window scrolls
    if (k % 2) tr.classList.add('alt');
    frag.appendChild(tr);
  }
  if (to < n) frag.appendChild(spacerRow(rowTop[n] - rowTop[to]));
  bodyEl.replaceChildren(frag);
  winFrom = from; winTo = to;

  // The first frame is laid out with estimated row heights; correct it once from the measurement (once only, to avoid oscillation)
  if (force && !remeasuring && measureRows()) {
    remeasuring = true;
    layoutRows();
    mountWindow(true);
    remeasuring = false;
  }
}

/// Measure both row heights; returns true when they disagree with the current assumption
function measureRows(): boolean {
  let changed = false;
  const r = bodyEl.querySelector('tr:not(.vspacer):not(.grp)') as HTMLElement | null;
  const g = bodyEl.querySelector('tr.grp') as HTMLElement | null;
  if (r?.offsetHeight && Math.abs(r.offsetHeight - hRow) > 0.5) { hRow = r.offsetHeight; changed = true; }
  if (g?.offsetHeight && Math.abs(g.offsetHeight - hGrp) > 0.5) { hGrp = g.offsetHeight; changed = true; }
  return changed;
}

