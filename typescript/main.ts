const verdictTimers: Record<string, number> = {};
/// Path health check (debounced): does it exist, is it a directory, are the two roots identical/nested.
/// Getting a root wrong is too costly to discover only at Compare time.
/// The editor and the main path row share this one implementation — both verdicts must be identical.
function scheduleVerdict(
  key: string,
  sEl: HTMLInputElement | null,
  tEl: HTMLInputElement | null,
  box: HTMLElement | null,
) {
  if (verdictTimers[key]) clearTimeout(verdictTimers[key]);
  verdictTimers[key] = window.setTimeout(async () => {
    if (!box) return;
    const s = sEl?.value ?? '';
    const t = tEl?.value ?? '';
    if (!s && !t) { box.innerHTML = ''; return; }
    try {
      const v = await invoke<PathVerdict>('inspect_paths', { source: s, target: t });
      const mark = (el: HTMLInputElement | null, info: PathInfo, val: string) => {
        if (!el) return;
        el.classList.toggle('bad', !!val.trim() && !info.is_dir);
        el.classList.toggle('good', info.is_dir);
      };
      mark(sEl, v.source, s);
      mark(tEl, v.target, t);
      const marks = [
        v.source.has_marker ? 'source has a .syncdash-root marker' : '',
        v.target.has_marker ? 'target has a .syncdash-root marker' : '',
      ].filter(Boolean).join(' · ');
      box.innerHTML =
        v.warnings.map((w) => `<div class="vwarn">⚠ ${escapeHtml(w)}</div>`).join('') +
        (marks ? `<div class="vok">✓ ${escapeHtml(marks)}</div>` : '');
    } catch { /* a failed check must not block editing */ }
  }, 300);
}
const edVerdict = () => scheduleVerdict('ed', edInput('source'), edInput('target'), document.getElementById('ed-verdict'));

