/// keepScroll: in-place actions like folding a directory or ticking a box stay put; only a filter change jumps back to the top
function renderTable(keepScroll = false) {
  // The identical-items panel owns the table area and sameShow controls its visibility — otherwise one
  // chip click would bring the diff table back and stack the two tables on top of each other
  if (sameOpen()) return;
  invalidateVis();
  const has = !!plan && plan.ops.length > 0;
  filterBar.classList.toggle('hidden', !has);
  tableEl.classList.toggle('hidden', !has);
  emptyEl.classList.toggle('hidden', has);
  if (!has) {
    rowPlan = [];
    bodyEl.replaceChildren();
    emptyEl.textContent = plan ? '✓ Both sides are identical — nothing to synchronize' : '← Select a job, then Compare (Ctrl+R)';
    return;
  }

  const vis = visibleIdx();
  // This pass only decides which rows show; it builds no nodes — mountWindow mounts the DOM per viewport
  rowPlan = [];
  // Always flat while sorting: grouping relies on the invariant that same-directory rows are consecutive in the plan, and sorting destroys it
  if (!grouped || sort) {
    lastGroupDirs = [];
    for (const i of vis) rowPlan.push({ kind: 'row', i, groupDir: null });
  } else {
    // Group consecutive same-directory rows (the plan is in walk order, and filtering keeps consecutive subsequences)
    const groups: { dir: string; items: number[] }[] = [];
    for (const i of vis) {
      const d = dirOf(eff(i).path);
      if (!groups.length || groups[groups.length - 1].dir !== d) groups.push({ dir: d, items: [] });
      groups[groups.length - 1].items.push(i);
    }
    lastGroupDirs = [...new Set(groups.map((g) => g.dir))];
    for (const g of groups) {
      rowPlan.push({ kind: 'grp', dir: g.dir, items: g.items });
      if (!collapsedDirs.has(g.dir)) {
        for (const i of g.items) rowPlan.push({ kind: 'row', i, groupDir: g.dir });
      }
    }
  }
  layoutRows();
  if (!keepScroll) wrapEl.scrollTop = 0;
  mountWindow(true);
  syncHeadCheckbox();
  renderStats();
  renderCounts();
  renderSortMarks();
}

